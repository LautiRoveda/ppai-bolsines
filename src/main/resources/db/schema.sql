-- PPAI Bolsines - Grupo 10 - CU 28 Registrar recepcion de bolsin
-- Esquema de la base PostgreSQL. Lo ejecuta InicializadorBaseDeDatos.reiniciar().
-- Las tablas salen del diagrama de clases de analisis y de diseno.
-- =====================================================================

DROP TABLE IF EXISTS cambio_estado_documentacion CASCADE;
DROP TABLE IF EXISTS detalle_remito CASCADE;
DROP TABLE IF EXISTS documentacion CASCADE;
DROP TABLE IF EXISTS remito CASCADE;
DROP TABLE IF EXISTS cambio_estado_bolsin CASCADE;
DROP TABLE IF EXISTS bolsin CASCADE;
DROP TABLE IF EXISTS tipo_documento CASCADE;
DROP TABLE IF EXISTS estado CASCADE;
DROP TABLE IF EXISTS sesion CASCADE;
DROP TABLE IF EXISTS usuario CASCADE;
DROP TABLE IF EXISTS empleado CASCADE;
DROP TABLE IF EXISTS comision_medica CASCADE;

-- ComisionMedica
CREATE TABLE comision_medica (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo    VARCHAR(20)  NOT NULL,
    nombre    VARCHAR(100) NOT NULL,
    direccion VARCHAR(200),
    email     VARCHAR(100),
    telefono  VARCHAR(50)
);

-- Empleado (asignado a una comision medica)
CREATE TABLE empleado (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    apellido           VARCHAR(100) NOT NULL,
    nombre             VARCHAR(100) NOT NULL,
    email              VARCHAR(100),
    comision_medica_id BIGINT NOT NULL REFERENCES comision_medica(id)
);

-- Usuario (cada usuario es de un empleado)
CREATE TABLE usuario (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      VARCHAR(50)  NOT NULL,
    password    VARCHAR(100) NOT NULL,
    fecha_alta  TIMESTAMP    NOT NULL,
    empleado_id BIGINT NOT NULL REFERENCES empleado(id)
);

-- Sesion (la activa indica quien es el usuario logueado)
CREATE TABLE sesion (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    esta_activa BOOLEAN NOT NULL,
    usuario_id  BIGINT NOT NULL REFERENCES usuario(id)
);

-- Estado: SOLO para bolsines y remitos (ambito = 'Bolsin' o 'Remito').
-- La documentacion NO usa esta tabla: usa el patron State.
CREATE TABLE estado (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      VARCHAR(100) NOT NULL,
    descripcion VARCHAR(200),
    ambito      VARCHAR(50)  NOT NULL
);

-- TipoDocumento
CREATE TABLE tipo_documento (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      VARCHAR(100) NOT NULL,
    descripcion VARCHAR(200)
);

-- Bolsin. La columna version la usa JPA (@Version) para que dos usuarios no puedan
-- registrar a la vez la recepcion del mismo bolsin.
CREATE TABLE bolsin (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_bolsin   INTEGER   NOT NULL,
    numero_precinto INTEGER   NOT NULL,
    fecha           TIMESTAMP NOT NULL,
    peso            DOUBLE PRECISION NOT NULL,
    cm_origen_id    BIGINT NOT NULL REFERENCES comision_medica(id),
    cm_destino_id   BIGINT NOT NULL REFERENCES comision_medica(id),
    version         INTEGER NOT NULL DEFAULT 0
);

-- CambioEstadoBolsin: historial del bolsin. El actual tiene fecha_hora_fin NULL.
CREATE TABLE cambio_estado_bolsin (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_hora_inicio TIMESTAMP NOT NULL,
    fecha_hora_fin    TIMESTAMP,
    bolsin_id         BIGINT NOT NULL REFERENCES bolsin(id),
    estado_id         BIGINT NOT NULL REFERENCES estado(id),
    responsable_ce_id BIGINT NOT NULL REFERENCES empleado(id)
);

-- Remito (guarda solo su estado actual, sin historial, como en el modelo)
CREATE TABLE remito (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero        INTEGER   NOT NULL,
    fecha         TIMESTAMP NOT NULL,
    bolsin_id     BIGINT REFERENCES bolsin(id),
    cm_origen_id  BIGINT NOT NULL REFERENCES comision_medica(id),
    cm_destino_id BIGINT NOT NULL REFERENCES comision_medica(id),
    estado_id     BIGINT NOT NULL REFERENCES estado(id)
);

-- Documentacion. PATRON STATE: estado_actual guarda el NOMBRE del estado concreto
-- (por ejemplo 'EnBolsinEnviado'). No hay tabla de estados de documentacion.
CREATE TABLE documentacion (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero            INTEGER      NOT NULL,
    asunto            VARCHAR(200) NOT NULL,
    fecha_pase        TIMESTAMP,
    tipo_documento_id BIGINT NOT NULL REFERENCES tipo_documento(id),
    cm_origen_id      BIGINT REFERENCES comision_medica(id),
    estado_actual     VARCHAR(50)  NOT NULL
);

-- DetalleRemito: une un remito con una documentacion
CREATE TABLE detalle_remito (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    area_cmc_destino VARCHAR(100),
    remito_id        BIGINT NOT NULL REFERENCES remito(id),
    documentacion_id BIGINT NOT NULL REFERENCES documentacion(id)
);

-- CambioEstadoDocumentacion: historial de la documentacion.
-- estado guarda el NOMBRE del estado concreto. El actual tiene fecha_hora_fin NULL.
CREATE TABLE cambio_estado_documentacion (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_hora_inicio TIMESTAMP   NOT NULL,
    fecha_hora_fin    TIMESTAMP,
    estado            VARCHAR(50) NOT NULL,
    documentacion_id  BIGINT NOT NULL REFERENCES documentacion(id),
    responsable_ce_id BIGINT NOT NULL REFERENCES empleado(id)
);
